// fallbackGlyph stands in for anything the font does not cover. A visible box
// is better than a hole: a missing glyph should look like a missing glyph.
const fallbackGlyph = "#####/#...#/#...#/#...#/#...#/#...#/#####"

// glyphRows returns the seven row patterns for a rune.
func glyphRows(r rune) []string {
	g, ok := glyphs[r]
	if !ok {
		g = fallbackGlyph
	}
	return strings.Split(g, "/")
}

// DrawGlyph draws one character with its top-left corner at (x,y), scaled by
// an integer factor. Pixels are set opaque; there is no anti-aliasing, because
// a bitmap font scaled by whole pixels does not need any.
func DrawGlyph(dst *image.RGBA, x, y int, r rune, col color.Color, scale int) {
	if scale < 1 {
		scale = 1
	}
	rows := glyphRows(r)
	c := color.RGBAModel.Convert(col).(color.RGBA)
	b := dst.Bounds()

	for ry, row := range rows {
		for rx := 0; rx < len(row); rx++ {
			if row[rx] != '#' {
				continue
			}
			for dy := 0; dy < scale; dy++ {
				for dx := 0; dx < scale; dx++ {
					px := x + rx*scale + dx
					py := y + ry*scale + dy
					if px < b.Min.X || py < b.Min.Y || px >= b.Max.X || py >= b.Max.Y {
						continue
					}
					dst.SetRGBA(px, py, c)
				}
			}
		}
	}
}

// DrawString draws text with its top-left corner at (x,y).
func DrawString(dst *image.RGBA, x, y int, s string, col color.Color, scale int) {
	if scale < 1 {
		scale = 1
	}
	for _, r := range s {
		DrawGlyph(dst, x, y, r, col, scale)
		x += GlyphAdvance * scale
	}
}

// StringWidth reports how wide a string will be drawn.
func StringWidth(s string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	// The last glyph contributes its width but not the trailing gap.
	return (n*GlyphAdvance - (GlyphAdvance - GlyphW)) * scale
}
